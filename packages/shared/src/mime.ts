export function contentTypeFor(path: string): string {
  const extension = path.split("/").pop()?.split(".").pop()?.toLowerCase() ?? ""
  return types[extension] ?? "application/octet-stream"
}

const textTypes = /^(text\/|application\/(json|xml|javascript|manifest\+json)|image\/svg)/

export const isTextContentType = (contentType: string) => textTypes.test(contentType)
